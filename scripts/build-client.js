#!/usr/bin/env node
/**
 * Build the hand-bundled browser client (see skills/creating-dsh-plugins).
 *
 * No bundler: the sources under src/client are inlined into one
 * `window.__ModuleLoader__.load({ id, factory })` call. `require` inside the
 * factory is the host module loader, so React (and the shell's primitives)
 * come from the shell instead of being bundled.
 *
 * Usage:  node settings-button/scripts/build-client.js [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const srcDir = join(root, 'src', 'client')
const outPath = join(root, 'lib', 'client.js')
const PLUGIN_ID = 'dsh-client-ui-settings-button'

/** Sources in dependency order: helpers first, the entry (which exports apply) last. */
const FILES = ['styles.js', 'menu.js', 'apply-guard.js', 'launcher.js', 'index.js']

/**
 * Strip module syntax; the bundle has no module system of its own.
 * @param {string} file - source file name under src/client.
 * @returns {string[]} transformed lines.
 */
function inline(file) {
  const lines = readFileSync(join(srcDir, file), 'utf8').split('\n')
  const out = []
  for (const line of lines) {
    if (/^\s*import\s/.test(line)) continue
    if (/^\s*export\s*\{[^}]*\}\s*;?\s*$/.test(line)) continue
    const match = line.match(/^(\s*)export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)/)
    out.push(match === null ? line : line.replace(/^(\s*)export\s+/, '$1'))
  }
  // Drop the blank runs the stripped imports leave at the top of a file.
  while (out.length > 0 && out[0].trim() === '') out.shift()
  return out
}

function build() {
  const sections = FILES.map((file) => inline(file).join('\n'))

  return `window.__ModuleLoader__.load({
  id: '${PLUGIN_ID}',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    // Generated by scripts/build-client.js - do not hand-edit.
    // Edit src/client/*.js and rebuild.
    const React = require('react')
${sections.map((section) => section.split('\n').map((line) => (line === '' ? '' : '    ' + line)).join('\n')).join('\n\n')}
    exports.apply = typeof apply === 'function' ? apply : (ctx) => {}
    exports.inject = typeof inject === 'undefined' ? [] : inject
    exports.__test = typeof __test === 'undefined' ? undefined : __test
    return exports
  },
})
`
}

const check = process.argv.includes('--check')
const built = build()
if (check) {
  let current = ''
  try {
    current = readFileSync(outPath, 'utf8')
  } catch {
    current = ''
  }
  if (current !== built) {
    console.error('lib/client.js is stale: run `node settings-button/scripts/build-client.js`')
    process.exit(1)
  }
  console.log('lib/client.js is up to date')
} else {
  writeFileSync(outPath, built)
  console.log(`wrote ${outPath} (${built.length} bytes)`)
}
